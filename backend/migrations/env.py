"""
Alembic environment for GridPulse.

Uses the app's own connection logic (app.database), so a migration reaches
the database exactly the way the API does: on the VM that is the Cloud SQL
private IP, with the password read from Secret Manager by the VM's service
account. No URL or password is written in alembic.ini.

Run from the backend/ directory (inside the image: /app/backend):
    alembic upgrade head
    alembic current
"""
import logging
import sys
from pathlib import Path

from alembic import context

# make `import app` work no matter where alembic is launched from
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

# Milestone 6: the migration's log lines are JSON on stdout too (same format as
# the API), so `Running upgrade -> 0001_initial_schema` shows up in Cloud Logging
# as a structured INFO entry instead of an unstructured line on stderr (which
# GKE would have tagged as ERROR).
from app.logging_config import setup_logging  # noqa: E402

setup_logging()
logging.getLogger("sqlalchemy.engine").setLevel(logging.WARNING)
logger = logging.getLogger("alembic.env")

config = context.config
target_metadata = None  # migrations are hand-written SQL, not autogenerated


def run_migrations_offline() -> None:
    """`alembic upgrade head --sql`: print the SQL, touch no database."""
    context.configure(
        url="postgresql://",
        dialect_name="postgresql",
        literal_binds=True,
        transaction_per_migration=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    from app.database import engine  # imported here so --sql never needs secrets

    logger.info("Target database: %s", engine.url.render_as_string(hide_password=True),
                extra={"event": "migration"})
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            transaction_per_migration=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
