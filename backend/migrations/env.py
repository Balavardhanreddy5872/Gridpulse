"""
Alembic environment for GridPulse.

Uses the app's own connection logic (app.database), so a migration reaches
the database exactly the way the API does: on the VM that is the Cloud SQL
private IP, with the password read from Secret Manager by the VM's service
account. No URL or password is written in alembic.ini.

Run from the backend/ directory (inside the image: /app/backend):
    alembic upgrade head
    alembic current
"""
import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context

# make `import app` work no matter where alembic is launched from
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)  # prints "Running upgrade -> 0001_initial_schema"
target_metadata = None  # migrations are hand-written SQL, not autogenerated


def run_migrations_offline() -> None:
    """`alembic upgrade head --sql`: print the SQL, touch no database."""
    context.configure(
        url="postgresql://",
        dialect_name="postgresql",
        literal_binds=True,
        transaction_per_migration=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    from app.database import engine  # imported here so --sql never needs secrets

    print(f"Target database: {engine.url.render_as_string(hide_password=True)}")
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            transaction_per_migration=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
